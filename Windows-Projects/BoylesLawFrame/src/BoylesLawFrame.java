    private void CalculateButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CalculateButton1ActionPerformed

        String find = cmbFind.getSelectedItem().toString();

        String missing = "";

        if (find.equals("P1")) {
            if (FinalPressureTextField.getText().trim().isEmpty()) {
                missing = missing + "- Final Pressure\n";
            }
            if (InitialVolumeTextField.getText().trim().isEmpty()) {
                missing = missing + "- Initial Volume\n";
            }
            if (FinalVolumeTextField.getText().trim().isEmpty()) {
                missing = missing + "- Final Volume\n";
            }
        } else if (find.equals("P2")) {
            if (InitialPressureTextField.getText().trim().isEmpty()) {
                missing = missing + "- Initial Pressure\n";
            }
            if (InitialVolumeTextField.getText().trim().isEmpty()) {
                missing = missing + "- Initial Volume\n";
            }
            if (FinalVolumeTextField.getText().trim().isEmpty()) {
                missing = missing + "- Final Volume\n";
            }
        } else if (find.equals("V1")) {
            if (InitialPressureTextField.getText().trim().isEmpty()) {
                missing = missing + "- Initial Pressure\n";
            }
            if (FinalPressureTextField.getText().trim().isEmpty()) {
                missing = missing + "- Final Pressure\n";
            }
            if (FinalVolumeTextField.getText().trim().isEmpty()) {
                missing = missing + "- Final Volume\n";
            }
        } else if (find.equals("V2")) {
            if (InitialPressureTextField.getText().trim().isEmpty()) {
                missing = missing + "- Initial Pressure\n";
            }
            if (FinalPressureTextField.getText().trim().isEmpty()) {
                missing = missing + "- Final Pressure\n";
            }
            if (InitialVolumeTextField.getText().trim().isEmpty()) {
                missing = missing + "- Initial Volume\n";
            }
        }

        // If anything is missing, show ALL of them at once and stop
        if (!missing.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Kindly fill:\n" + missing);
            return;
        }

        try {
            double initialPressure = 0;
            double finalPressure = 0;
            double initialVolume = 0;
            double finalVolume = 0;
            double result = 0;

            if (find.equals("P1")) {
                finalPressure = Double.parseDouble(FinalPressureTextField.getText());
                initialVolume = Double.parseDouble(InitialVolumeTextField.getText());
                finalVolume = Double.parseDouble(FinalVolumeTextField.getText());
                result = (finalPressure * finalVolume) / initialVolume;
                InitialPressureTextField.setText("" + result);
            } else if (find.equals("P2")) {
                initialPressure = Double.parseDouble(InitialPressureTextField.getText());
                initialVolume = Double.parseDouble(InitialVolumeTextField.getText());
                finalVolume = Double.parseDouble(FinalVolumeTextField.getText());
                result = (initialPressure * initialVolume) / finalVolume;
                FinalPressureTextField.setText("" + result);
            } else if (find.equals("V1")) {
                initialPressure = Double.parseDouble(InitialPressureTextField.getText());
                finalPressure = Double.parseDouble(FinalPressureTextField.getText());
                finalVolume = Double.parseDouble(FinalVolumeTextField.getText());
                result = (finalPressure * finalVolume) / initialPressure;
                InitialVolumeTextField.setText("" + result);
            } else if (find.equals("V2")) {
                initialPressure = Double.parseDouble(InitialPressureTextField.getText());
                finalPressure = Double.parseDouble(FinalPressureTextField.getText());
                initialVolume = Double.parseDouble(InitialVolumeTextField.getText());
                result = (initialPressure * initialVolume) / finalPressure;
                FinalVolumeTextField.setText("" + result);
            }

            ResultTextField.setText("" + result);

        } catch (NumberFormatException e) {
            ResultTextField.setText("Please Enter OnlyNumbers! NO Letters.");
        } catch (Exception e) {
            ResultTextField.setText("Something went wrong: " + e.getMessage());
        }

    }//GEN-LAST:event_CalculateButton1ActionPerformed

