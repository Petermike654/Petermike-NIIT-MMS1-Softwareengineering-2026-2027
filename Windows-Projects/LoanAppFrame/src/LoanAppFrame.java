    private void CalculateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CalculateButtonActionPerformed
       // AUTO SECURITY FOR ALPHABET - INSIDE CALCULATE BUTTON
String loanText = LoanAmountTextField.getText().trim();
String durationText = DurationTextField.getText().trim();

if (!loanText.matches("[0-9.]+")) {
    javax.swing.JOptionPane.showMessageDialog(null, "Loan Amount: Numbers Only! Alphabet is not allowed.");
    LoanAmountTextField.requestFocus();
    return;
}

if (!durationText.matches("[0-9]+")) {
    javax.swing.JOptionPane.showMessageDialog(null, "Duration: Numbers Only! Alphabet is not allowed.");
    DurationTextField.requestFocus();
    return;
}
        // --- SECURITY: CHECK EMPTY ---
        String missing = "";

        if (LoanAmountTextField.getText().trim().isEmpty()) {
            missing = missing + "- Loan Amount\n";
        }
        if (DurationTextField.getText().trim().isEmpty()) {
            missing = missing + "- Duration\n";
        }

        if (!missing.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Kindly fill:\n" + missing);
            return;
        }

// --- SECURITY: CHECK NUMBERS ONLY ---
        double loanAmount = 0;
        int duration = 0;

        try {
            loanAmount = Double.parseDouble(LoanAmountTextField.getText().trim());
            duration = Integer.parseInt(DurationTextField.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Please enter only numbers! No letters.");
            
            return;
        }

// --- SECURITY: CHECK ZERO / NEGATIVE / TOO BIG ---
        if (loanAmount <= 0) {
            JOptionPane.showMessageDialog(null, "Loan Amount cannot be 0 or negative!");
            return;
        }
        if (duration <= 0) {
            JOptionPane.showMessageDialog(null, "Duration cannot be 0 or negative!");
            return;
        }
        if (duration > 60) {
            JOptionPane.showMessageDialog(null, "Duration cannot be more than 60 months!");
            return;
        }

// --- CALCULATION: 1.5% ON REDUCING BALANCE ---
        double principalPerMonth = loanAmount / duration;
        double balance = loanAmount;
        double totalInterest = 0;
        double totalRepayment = 0;

        DefaultTableModel model = (DefaultTableModel) LoanTable.getModel();
        model.setRowCount(0);

        for (int month = 1; month <= duration; month++) {
            double interest = balance * 0.015;
            double monthlyRepayment = principalPerMonth + interest;

            totalInterest = totalInterest + interest;
            totalRepayment = totalRepayment + monthlyRepayment;

            model.addRow(new Object[]{
                month,
                String.format("%,.2f", principalPerMonth),
                String.format("%,.2f", interest),
                String.format("%,.2f", monthlyRepayment)
            });

            balance = balance - principalPerMonth;
        }

        TotalRepaymentTextField.setText(String.format("%,.2f", totalRepayment));
        TotalInterestTextField.setText(String.format("%,.2f", totalInterest));

    }//GEN-LAST:event_CalculateButtonActionPerformed

