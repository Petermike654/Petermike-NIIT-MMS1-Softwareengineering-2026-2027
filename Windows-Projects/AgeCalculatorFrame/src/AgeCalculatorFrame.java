    private void CalculateAgeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CalculateAgeButtonActionPerformed
        String dayText = BirthDayTextField.getText().trim();
        String monthText = BirthMonthTextField.getText().trim();
        String yearText = BirthYearTextField.getText().trim();

        if (dayText.equals("") || monthText.equals("") || yearText.equals("")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter Birthday, Birthmonth and Birthyear");
            return;
        }

        try {
            int birthDay = Integer.parseInt(dayText);
            int birthMonth = Integer.parseInt(monthText);
            int birthYear = Integer.parseInt(yearText);

            java.util.Calendar calendar = java.util.Calendar.getInstance();
            int currentDay = calendar.get(java.util.Calendar.DAY_OF_MONTH);
            int currentMonth = calendar.get(java.util.Calendar.MONTH) + 1;
            int currentYear = calendar.get(java.util.Calendar.YEAR);

            int years = currentYear - birthYear;
            int months = currentMonth - birthMonth;
            int days = currentDay - birthDay;

            if (days < 0) {
                months = months - 1;

                // Get correct days in previous month (handles leap year)
                int prevMonth = currentMonth - 1;
                int prevYear = currentYear;

                if (prevMonth == 0) {
                    prevMonth = 12;
                    prevYear = prevYear - 1;
                }

                days = days + getDaysInMonth(prevMonth, prevYear);
            }

            if (months < 0) {
                years = years - 1;
                months = months + 12;
            }

            YearsTextField.setText(String.valueOf(years));
            MonthsTextField.setText(String.valueOf(months));
            DaysTextField.setText(String.valueOf(days));

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter only numbers. Alphabet is not allowed");
        }
        
    }

// This method calculates correct days in a month (including leap year)
    private int getDaysInMonth(int month, int year) {
        if (month == 1 || month == 3 || month == 5 || month == 7
                || month == 8 || month == 10 || month == 12) {
            return 31;
        } else if (month == 4 || month == 6 || month == 9 || month == 11) {
            return 30;
        } else {
            // February - check leap year
            if ((year % 4 == 0 && year % 100 != 0) || (year % 400 == 0)) {
                return 29;   // Leap year
            } else {
                return 28;   // Normal year
            }
        }
    }//GEN-LAST:event_CalculateAgeButtonActionPerformed

