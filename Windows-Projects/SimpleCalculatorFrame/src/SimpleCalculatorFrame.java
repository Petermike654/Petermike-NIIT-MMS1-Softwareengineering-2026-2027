    private void EqualtobtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EqualtobtnActionPerformed
        try {
            if (selectedOperator.equals("")){
                javax.swing.JOptionPane.showMessageDialog(this, "Please select an operator(+, -, *, /)");
                return;
            }
            double firstNumber = Double.parseDouble(FirstNumberTextField.getText());
            double secondNumber = Double.parseDouble(SecondNumberTextField.getText());

            // You can decide what the = button should do.
            // For example, if you want it to add by default:
            double result = firstNumber + secondNumber;

            ResultTextField.setText(String.valueOf(result));

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Kindly, Fill in first Number and second Number to continue!");
        }
    }//GEN-LAST:event_EqualtobtnActionPerformed

    private void MutibtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MutibtnActionPerformed
        String firstNumberIsEmpty, secondNumberIsEmpty, selectedOperator;
        double firstNumber, secondNumber, result;
        OperatorLabel.setText("*"); // This will show * in the middle
        selectedOperator = "*";
        

        firstNumberIsEmpty = FirstNumberTextField.getText().trim();
        secondNumberIsEmpty = SecondNumberTextField.getText().trim();

        if (firstNumberIsEmpty.isEmpty() && secondNumberIsEmpty.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Kindly, Fill in first Number and second Number to continue",
                    "Error!",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        try {

            firstNumber = Double.parseDouble(firstNumberIsEmpty);
            secondNumber = Double.parseDouble(secondNumberIsEmpty);

            result = firstNumber * secondNumber;
            ResultTextField.setText(String.valueOf(result));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Unable to calculate",
                    "Error!",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_MutibtnActionPerformed

